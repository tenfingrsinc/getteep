function normalizeStrategy(strategy: DefiStrategy): DefiStrategy {
  const accessText = strategy.exitTimeEstimate.toLowerCase();
  const accessCategory: DefiStrategyAccess = strategy.accessCategory
    || (/longer|day|bridge|finality/.test(accessText)
      ? "longer"
      : /moderate|hour/.test(accessText)
        ? "moderate"
        : "fast");
  const availability: DefiStrategyAvailability = strategy.availability
    || (strategy.status === "ready" ? "live" : strategy.status === "disabled" ? "paused" : "preview");
  return {
    ...strategy,
    availability,
    accessCategory,
    description: strategy.description || `${strategy.provider} growth option`,
    tags: Array.isArray(strategy.tags) ? strategy.tags : [],
    disclosures: Array.isArray(strategy.disclosures) ? strategy.disclosures : [],
    controls: Array.isArray(strategy.controls) && strategy.controls.length
      ? strategy.controls
      : ["add", "withdraw_partial", "withdraw_all"],
    transactionEnabled: ENABLE_DEFI_TRANSACTIONS && DEFI_TRANSACTION_ROUTE_READY && strategy.status === "ready",
  };
}

export function listDefiStrategies(): DefiStrategy[] {
  return parseStrategiesFromEnv() || soulessStrategies();
}

export function getDefiStrategy(strategyId: string): DefiStrategy | null {
  return listDefiStrategies().find((strategy) => strategy.id === strategyId) || null;
}

export async function listDefiStrategyEvidence(): Promise<Record<string, DefiStrategyEvidence>> {
  const db = getDb();
  const participantRows = await db.prepare(
    `SELECT p.strategy_id, COUNT(DISTINCT LOWER(p.user_address)) AS participant_count, MAX(p.updated_at) AS updated_at
     FROM defi_positions p
     WHERE CAST(p.current_value_raw AS NUMERIC) > 0
       AND p.verification_source = 'chain_indexer'
       AND p.canonical = TRUE
     GROUP BY p.strategy_id`
  ).all() as Array<{ strategy_id: string; participant_count: number | string; updated_at: number | string }>;
  const yieldRows = await db.prepare(
    `SELECT strategy_id, COALESCE(SUM(CAST(amount_raw AS NUMERIC)), 0) AS yield_paid_raw, MAX(updated_at) AS updated_at
     FROM defi_transactions
     WHERE evidence_type = 'realized_service_fee'
       AND verification_source = 'chain_indexer'
       AND canonical = TRUE
       AND LOWER(status) IN ('complete', 'completed', 'confirmed', 'success')
       AND COALESCE(destination_tx_hash, source_tx_hash) IS NOT NULL
     GROUP BY strategy_id`
  ).all() as Array<{ strategy_id: string; yield_paid_raw: string | number; updated_at: number | string }>;
  const avatarRows = await db.prepare(
    `SELECT p.strategy_id, LOWER(p.user_address) AS user_address, MAX(p.updated_at) AS updated_at
     FROM defi_positions p
     LEFT JOIN user_settings s ON LOWER(s.address) = LOWER(p.user_address)
     WHERE CAST(p.current_value_raw AS NUMERIC) > 0
       AND p.verification_source = 'chain_indexer'
       AND p.canonical = TRUE
       AND COALESCE(s.privacy_hide_growth_activity, FALSE) = FALSE
     GROUP BY p.strategy_id, LOWER(p.user_address)
     ORDER BY updated_at DESC`
  ).all() as Array<{ strategy_id: string; user_address: string; updated_at: number | string }>;

  const yieldByStrategy = new Map(yieldRows.map((row) => [row.strategy_id, row]));
  const avatarAddresses = Array.from(new Set(avatarRows.map((row) => row.user_address))).slice(0, 100);
  const identities = await resolveAddressIdentities(avatarAddresses);
  const result: Record<string, DefiStrategyEvidence> = {};

  for (const participantRow of participantRows) {
    const yieldRow = yieldByStrategy.get(participantRow.strategy_id);
    const participantCount = Number(participantRow.participant_count || 0);
    const yieldPaidRaw = String(yieldRow?.yield_paid_raw || "0").split(".")[0] || "0";
    if (participantCount <= 0 || BigInt(yieldPaidRaw) <= 0n) continue;
    const participants = avatarRows
      .filter((row) => row.strategy_id === participantRow.strategy_id)
      .slice(0, 3)
      .map((row) => identities.get(row.user_address))
      .filter((identity): identity is NonNullable<typeof identity> => Boolean(identity))
      .map((identity) => ({
        displayName: identity.displayName,
        profileImageUrl: identity.profileImageUrl,
      }));
    result[participantRow.strategy_id] = {
      participantCount,
      yieldPaidRaw,
      updatedAt: Math.max(Number(participantRow.updated_at || 0), Number(yieldRow?.updated_at || 0)),
      participants,
    };
  }

  return result;
}

export function getDefiSummary() {
  const strategies = listDefiStrategies();
  const readyStrategyCount = strategies.filter((strategy) => strategy.status === "ready").length;
  const transactionEnabled = ENABLE_DEFI_TRANSACTIONS && strategies.some((strategy) => strategy.transactionEnabled);
  const configuredCommunityTotalRaw = process.env.DEFI_COMMUNITY_TOTAL_RAW?.trim();
  const configuredParticipantCount = Number(process.env.DEFI_PARTICIPANT_COUNT || 0);
  const strategyParticipantCount = strategies.reduce((sum, strategy) => sum + Number(strategy.participantCount || 0), 0);
  const communityTotalRaw = configuredCommunityTotalRaw || undefined;
  const participantCount = configuredParticipantCount > 0
    ? configuredParticipantCount
    : strategyParticipantCount > 0
      ? strategyParticipantCount
      : undefined;
  return {
    mode: transactionEnabled ? "transactions_enabled" : "preview_only",
    transactionEnabled,
    strategyCount: strategies.length,
    readyStrategyCount,
    providerCount: new Set(strategies.map((strategy) => strategy.provider)).size,
    communityTotalRaw,
    participantCount,
    guardrails: [
      "No beta transaction route is enabled unless ENABLE_DEFI_TRANSACTIONS=true.",
      "Wallet actions remain unavailable unless DEFI_TRANSACTION_ROUTE_READY=true.",
      "Strategies are configured by provider metadata, not hardcoded into frontend flows.",
      "Provider deployment addresses must be verified before a strategy can move to ready.",
    ],
  };
}

export async function listPreviewPositions(address: string): Promise<DefiPreviewPosition[]> {
  const db = getDb();
  const rows = await db
    .prepare(
      `SELECT id, strategy_id, principal_raw, current_value_raw, yield_earned_raw, shares_raw,
              target_address, verification_source, chain_state, updated_at
       FROM defi_positions
       WHERE lower(user_address) = lower(?)
         AND canonical = TRUE
       ORDER BY updated_at DESC`
    )
    .all(address) as Array<{
      id: string;
      strategy_id: string;
      principal_raw: string;
      current_value_raw: string;
      yield_earned_raw: string;
      shares_raw: string | null;
      target_address: string | null;
      verification_source: string | null;
      chain_state: string;
      updated_at: number;
    }>;

  if (rows.length > 0) {
    const client = createBackendPublicClient({ timeoutMs: Number(process.env.DISPLAY_RPC_TIMEOUT_MS || 4_000) });
    return Promise.all(rows.map(async (row) => {
      let currentValueRaw = row.current_value_raw;
      let updatedAt = row.updated_at;
      if (
        row.verification_source === "chain_indexer" &&
        row.target_address && isAddress(row.target_address) &&
        BigInt(row.shares_raw || "0") > 0n
      ) {
        try {
          const value = await client.readContract({
            address: getAddress(row.target_address) as `0x${string}`,
            abi: STRATEGY_PREVIEW_ABI,
            functionName: "previewRedeem",
            args: [BigInt(row.shares_raw || "0")],
          });
          currentValueRaw = value.toString();
          updatedAt = Date.now();
        } catch {
          // Indexed state remains the display fallback when fresh RPC reads fail.
        }
      }
      return {
        id: row.id,
        strategyId: row.strategy_id,
        status: "indexed" as const,
        principalRaw: row.principal_raw,
        currentValueRaw,
        yieldEarnedRaw: row.yield_earned_raw,
        chainState: row.chain_state,
        updatedAt,
      };
    }));
  }

  return [];
}

export async function listDefiActivity(address: string): Promise<DefiActivityRecord[]> {
  const db = getDb();
  const strategies = new Map(listDefiStrategies().map((strategy) => [strategy.id, strategy]));
  const rows = await db
    .prepare(
      `SELECT id, strategy_id, action, status, source_tx_hash, destination_tx_hash, amount_raw, error, metadata_json, created_at
       FROM defi_transactions
       WHERE lower(user_address) = lower(?)
         AND canonical = TRUE
       ORDER BY created_at DESC
       LIMIT 100`
    )
    .all(address) as Array<{
      id: string;
      strategy_id: string;
      action: string;
      status: string;
      source_tx_hash: string | null;
      destination_tx_hash: string | null;
      amount_raw: string | null;
      error: string | null;
      metadata_json: string | null;
      created_at: number;
    }>;

  if (rows.length > 0) {
    return rows.map((row) => {
      const strategy = strategies.get(row.strategy_id);
      const action = normalizeActivityAction(row.action);
      return {
        id: row.id,
        timestamp: row.created_at,
        action,
        strategyId: row.strategy_id,
        strategyName: strategy?.name || row.strategy_id,
        amountRaw: row.amount_raw || "0",
        direction: action === "withdraw" ? "out" : action === "details" || action === "watch" ? "neutral" : "in",
        status: normalizeActivityStatus(row.status),
        txHash: row.destination_tx_hash || row.source_tx_hash || undefined,
        detail: row.error || undefined,
      };
    });
  }

  return [];
}

function normalizeActivityAction(action: string): DefiActivityRecord["action"] {
  const normalized = action.toLowerCase();
  if (["deposit", "grow", "supply"].includes(normalized)) return "grow";
  if (["yield", "harvest", "interest"].includes(normalized)) return "yield";
  if (["withdraw", "exit", "redeem"].includes(normalized)) return "withdraw";
  if (["details", "view_details"].includes(normalized)) return "details";
  if (["watch", "watch_strategy"].includes(normalized)) return "watch";
  return "grow";
}

function normalizeActivityStatus(status: string): DefiActivityRecord["status"] {
  const normalized = status.toLowerCase();
  if (["pending", "processing"].includes(normalized)) return "pending";
  if (["complete", "completed", "confirmed", "success"].includes(normalized)) return "complete";
  if (["failed", "error"].includes(normalized)) return "failed";
  return "preview";
}
