function configuredAddress(name: string): string | undefined {
  const value = process.env[name]?.trim();
  return value && isAddress(value) && getAddress(value) !== ZeroAddress ? getAddress(value) : undefined;
}

function configuredSoulessStrategyId(): string {
  const value = process.env.DEFI_SOULESS_STRATEGY_ID?.trim() || "SOULESS_V3_GROWTH_73A95B_V1";
  return /^0x[0-9a-fA-F]{64}$/.test(value) ? value.toLowerCase() : hashText(value).toLowerCase();
}

function soulessStrategyStatus(): DefiStrategy["status"] {
  if (process.env.DEFI_SOULESS_STATUS === "disabled") return "disabled";
  const deploymentConfigured = Boolean(
    configuredAddress("DEFI_SOULESS_VAULT_ADDRESS") &&
    configuredAddress("DEFI_SOULESS_ADAPTER_ADDRESS") &&
    configuredAddress("DEFI_SOULESS_POOL_ADDRESS")
  );
  const verified = process.env.DEFI_SOULESS_DEPLOYMENT_VERIFIED === "true";
  const indexed = process.env.DEFI_SOULESS_INDEXED === "true";
  return process.env.DEFI_SOULESS_STATUS === "ready" && deploymentConfigured && verified && indexed
    ? "ready"
    : "pending_provider";
}

